"""The labelled corpus: which transitions are measured, and which are not, and why.

A *transition* is one pair of consecutive versions of one act, together with the amending acts
whose modification annotations fall in the window `(date(A), date(B)]`. That window, not the
amending act, is what a version pair asks about: a pair can fold in several amending acts, and
one amending act's changes can be split across several dates.

Nothing here is hand-authored. The case list is generated from the acts' own tree notices and
branch notices by the rules below, and `corpus.json` is the committed result:

1. **Consecutive readable versions.** A version the corpus publishes no English Formex for is
   stepped over, never silently: it is recorded as a skip, and the case that bridges it lists it
   in `bridged`. The question worth asking is what changed since the last text a reader could
   actually see, and the metadata window folds in every amending act between the two. Without
   this rule the flagship transition would not exist at all — the AI Act's middle consolidation is
   published in eleven languages, English not among them.
2. **All of the AI Act, the MDR and the DSA; a sample of REACH**. REACH has 60+ usable
   transitions and pinning both texts of each would cost tens of megabytes for no extra evidence,
   so ten are taken by `sample_indices` — evenly spread over the whole history, endpoints included,
   deterministic, and depending on nothing but the sorted list length.
3. **Coverage is a fraction, never an implication.** Every act records how many transitions it has
   and how many were selected; every unusable version records the first-class state that made it
   unusable. A sample is published as the fraction it is, never as a claim about the whole.

The third signal (the amending act's own instructions) is computed only where the window names
**exactly one** amending act and that act's own Formex is small enough to commit (`build.py`).
Everywhere else it is `UNAVAILABLE`, which is silence and not dissent, and the report publishes
the fraction.
"""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path
from typing import Final

from pydantic import BaseModel, ConfigDict, Field

__all__ = [
    "CORPUS_PATH",
    "FLAGSHIP_CASE",
    "REACH_SAMPLE",
    "SUBSET_SAMPLE",
    "CaseInput",
    "CorpusAct",
    "CorpusCase",
    "CorpusSkip",
    "EvalCorpus",
    "ExplainSubset",
    "SubsetCase",
    "load_corpus",
    "sample_indices",
    "write_corpus",
]

CORPUS_PATH: Final = Path(__file__).resolve().parent / "corpus.json"
"""The committed labelled set. Generated by `emendrix eval build-corpus`, read by everything."""

REACH_SAMPLE: Final = 10
"""The documented REACH sample size. The other three acts contribute every transition."""

FLAGSHIP_CASE: Final = "32024R1689@20260727"
"""The AI Act / Digital Omnibus transition. Every explainable change of it is in the subset."""

SUBSET_SAMPLE: Final = 10
"""How many further changes the explanation subset takes from the rest of the corpus."""


def sample_indices(total: int, wanted: int) -> tuple[int, ...]:
    """`wanted` indices spread evenly over `range(total)`, endpoints included.

    Deterministic and dependent only on two integers — no dict ordering, no set iteration, no
    seed, no clock. `sample_indices(61, 10)` is `(0, 7, 13, 20, 27, 33, 40, 47, 53, 60)`: the
    oldest transition, the newest, and eight evenly between them.
    """
    if wanted <= 0 or total <= 0:
        return ()
    if wanted >= total:
        return tuple(range(total))
    if wanted == 1:
        return (0,)
    return tuple(sorted({round(index * (total - 1) / (wanted - 1)) for index in range(wanted)}))


class CaseInput(BaseModel):
    """One document a case is computed from, pinned by digest.

    The digest is of the *committed* bytes — trimmed by the rules in `eu/trims.py`, whose
    untrimmed source digest the fixture manifest records beside it. A case whose inputs hash
    differently is not the case that was measured.
    """

    model_config = ConfigDict(frozen=True)

    role: str = Field(description="`from`, `to`, `metadata` or `instructions`.")
    url: str
    sha256: str
    size: int = Field(ge=0)


class CorpusCase(BaseModel):
    """One measured transition: two versions of one act, and the labels for the window."""

    model_config = ConfigDict(frozen=True)

    id: str = Field(description="`32024R1689@20260727` — the act and the version it moves to.")
    act: str = Field(description="CELEX of the amended act.")
    act_title: str | None = None
    from_version: str
    to_version: str
    from_date: date | None = None
    to_date: date
    from_original: bool = Field(
        default=False,
        description="True when `from_version` is the act as published, so the window has no floor.",
    )
    bridged: tuple[str, ...] = Field(
        default=(), description="Versions between the two whose text the corpus does not publish."
    )
    amending_acts: tuple[str, ...] = Field(
        default=(), description="Amending CELEXes whose annotations fall in this window."
    )
    annotations: int = Field(default=0, ge=0, description="Annotation count in the window.")
    instruction_source: str | None = Field(
        default=None, description="The amending act whose own Formex supplies the third signal."
    )
    instruction_note: str = Field(
        default="", description="Why the third signal is unavailable, when it is."
    )
    selection: str = Field(default="all", description="Why this transition is in the corpus.")
    inputs: tuple[CaseInput, ...] = ()


class CorpusSkip(BaseModel):
    """A transition that does not exist, and the first-class state that is the reason."""

    model_config = ConfigDict(frozen=True)

    act: str
    version: str
    version_date: date | None = None
    reason: str = Field(description="A first-class state name, e.g. `structured_text_unavailable`.")
    detail: str = ""


class CorpusAct(BaseModel):
    """One act's contribution, stated as a fraction of what it could have contributed."""

    model_config = ConfigDict(frozen=True)

    celex: str
    title: str | None = None
    versions: int = Field(default=0, ge=0)
    versions_usable: int = Field(default=0, ge=0, description="Versions with English Formex.")
    transitions_possible: int = Field(default=0, ge=0)
    transitions_selected: int = Field(default=0, ge=0)
    annotations: int = Field(default=0, ge=0, description="Modification annotations in the notice.")
    amending_acts: int = Field(default=0, ge=0)
    note: str = ""

    @property
    def coverage(self) -> float:
        """Selected over possible. `1.0` for an act with no transitions to select from."""
        if self.transitions_possible == 0:
            return 1.0
        return self.transitions_selected / self.transitions_possible


class SubsetCase(BaseModel):
    """One transition's contribution to the explanation subset, pinned by unit location.

    Explicit locations rather than indices or a rule to re-run: a change that stops appearing in
    a delta then shows up in the report as a *named missing unit* instead of quietly shrinking
    the denominator a grounding rate is computed over.
    """

    model_config = ConfigDict(frozen=True)

    case_id: str
    selection: str = Field(description="Why these units are in the subset, in one phrase.")
    units: tuple[str, ...] = Field(
        min_length=1, description="Canonical locations, in the delta's own order."
    )


class ExplainSubset(BaseModel):
    """The pinned set of changes the model layer is measured over (`subset.py` selects it).

    Small on purpose: every unit in it is a recorded exchange with a provider, committed to the
    repository and replayed in CI. The selection rule is committed with it so that re-running
    the rule is the only way to change the set. Picking cases after seeing a grounding rate is
    curating the corpus to the answer, which this project never does.
    """

    model_config = ConfigDict(frozen=True)

    note: str = ""
    flagship: str = FLAGSHIP_CASE
    sample: int = Field(default=SUBSET_SAMPLE, ge=0)
    cases: tuple[SubsetCase, ...] = ()

    @property
    def changes(self) -> int:
        """How many exchanges a full recording run costs."""
        return sum(len(case.units) for case in self.cases)

    def units_for(self, case_id: str) -> tuple[str, ...]:
        for case in self.cases:
            if case.case_id == case_id:
                return case.units
        return ()


class EvalCorpus(BaseModel):
    """The whole committed labelled set: what is measured, what is not, and when it was built."""

    model_config = ConfigDict(frozen=True)

    built_on: date
    note: str = ""
    acts: tuple[CorpusAct, ...] = ()
    cases: tuple[CorpusCase, ...] = ()
    skips: tuple[CorpusSkip, ...] = ()
    explain_subset: ExplainSubset | None = Field(
        default=None,
        description="The pinned changes the model layer is measured over. `emendrix eval "
        "build-subset` writes it; `None` means no model-layer run is possible.",
    )

    def case(self, case_id: str) -> CorpusCase | None:
        return next((item for item in self.cases if item.id == case_id), None)

    def cases_of(self, act: str) -> tuple[CorpusCase, ...]:
        return tuple(item for item in self.cases if item.act == act)

    @property
    def transitions_possible(self) -> int:
        return sum(act.transitions_possible for act in self.acts)

    @property
    def coverage(self) -> float:
        """Cases over transitions the four acts offer. A fraction, stated and never implied."""
        possible = self.transitions_possible
        return 1.0 if possible == 0 else len(self.cases) / possible


def load_corpus(path: Path = CORPUS_PATH) -> EvalCorpus:
    return EvalCorpus.model_validate_json(path.read_bytes())


def write_corpus(corpus: EvalCorpus, path: Path = CORPUS_PATH) -> None:
    """Write the corpus pretty-printed and key-sorted, so a re-generation diffs readably."""
    path.write_text(
        json.dumps(corpus.model_dump(mode="json"), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
