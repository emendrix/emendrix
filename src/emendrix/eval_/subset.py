"""Choosing the pinned explanation subset, and cutting a delta down to it.

The deterministic layers are scored over every transition in the corpus because that costs
nothing but CPU. The model layers cannot be: every change in the subset is one recorded exchange
with a provider, committed to the repository and replayed in CI, so the set has to be small,
fixed, and chosen by a rule rather than by a person looking at results.

The rule is two lines, and the second reuses the corpus sampler:

1. **Every explainable change of the flagship transition.** The AI Act / Digital Omnibus pair is
   the one the deterministic layers score at F1 = 1.000 (asserted by
   `tests/corroborate/test_eu_corroboration.py`), so a grounding number measured over it
   is not contaminated by localisation error — whatever the gate rejects, it rejects about a
   provision that genuinely changed.
2. **Ten more, spread evenly over everything else**, by the same `sample_indices` the corpus
   itself is selected with: no seed, no clock, no dict ordering, reproducible from two integers.
   Deliberately *not* "ten interesting ones": picking the sample after seeing the grounding rate
   is curating the corpus to the answer, which this project never does.

Textless changes are never sampled. The corroborator appends one per unit another signal named
and the diff did not, and they reach the explain stage with nothing to explain, so there is no
exchange to record for them. They are counted by the deterministic layer instead.

No clock, no network, no model here: the selection is a pure function of the deltas it is given.
"""

from __future__ import annotations

from collections.abc import Iterable, Sequence

from emendrix.core import Delta
from emendrix.eval_.corpus import (
    FLAGSHIP_CASE,
    SUBSET_SAMPLE,
    ExplainSubset,
    SubsetCase,
    sample_indices,
)
from emendrix.explain import explainable

__all__ = ["FLAGSHIP_NOTE", "restrict", "select_subset"]

FLAGSHIP_NOTE = "every explainable change of the flagship transition"


def _explainable_units(delta: Delta) -> tuple[str, ...]:
    return tuple(change.location.canonical for change in delta.changes if explainable(change))


def select_subset(
    deltas: Sequence[tuple[str, Delta]],
    *,
    flagship: str = FLAGSHIP_CASE,
    sample: int = SUBSET_SAMPLE,
) -> ExplainSubset:
    """Choose the subset from every case's delta. Deterministic given the same deltas.

    `deltas` arrives in corpus order and stays in it; the pooled sample is taken over the
    concatenation of every non-flagship case's explainable units, so it depends on neither how
    many cases an act contributes nor the order a dictionary happened to iterate in.
    """
    flagship_case: list[SubsetCase] = []
    pool: list[tuple[str, str]] = []
    for case_id, delta in deltas:
        units = _explainable_units(delta)
        if case_id == flagship:
            if units:
                flagship_case.append(
                    SubsetCase(case_id=case_id, selection=FLAGSHIP_NOTE, units=units)
                )
            continue
        pool.extend((case_id, unit) for unit in units)
    picked = sample_indices(len(pool), sample)
    note = f"sample of {len(picked)} from {len(pool)}, evenly spread over the other transitions"
    sampled = [
        SubsetCase(case_id=case_id, selection=note, units=chosen)
        for case_id, _ in deltas
        if (chosen := tuple(pool[index][1] for index in picked if pool[index][0] == case_id))
    ]
    return ExplainSubset(
        note=(
            f"Generated by `emendrix eval build-subset`: {FLAGSHIP_NOTE} ({flagship}), plus a "
            f"{note}. Nothing in it was chosen by hand or after seeing a result."
        ),
        flagship=flagship,
        sample=sample,
        cases=tuple(flagship_case + sampled),
    )


def restrict(delta: Delta, units: Iterable[str]) -> tuple[Delta, tuple[str, ...]]:
    """`(the delta with only the named units, the named units the delta does not have)`.

    A unit the subset names and the delta does not is reported, never silently dropped: it means
    the diff moved under a pinned set, which is a finding rather than a smaller denominator.
    """
    wanted = tuple(units)
    keep = frozenset(wanted)
    changes = tuple(change for change in delta.changes if change.location.canonical in keep)
    found = {change.location.canonical for change in changes}
    missing = tuple(unit for unit in wanted if unit not in found)
    return delta.model_copy(update={"changes": changes}), missing
