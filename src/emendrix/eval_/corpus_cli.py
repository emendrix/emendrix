"""`emendrix eval build-corpus | build-subset` — choosing what gets measured.

Split from `cli.py` along the job rather than along the line count. These two commands *build*
the labelled set: they own the network boundary (`build-corpus` is the only command in the
project outside the fetch path that may reach CELLAR), they pin the fixture documents by digest,
and they decide which changes the model layer will later be scored over. Nothing here scores
anything. `cli.py` holds the other half, which reads what these wrote and publishes numbers from
it, and mounts both halves on the one `emendrix eval` app.

The pair runs in this order, and only in it: `build-corpus` writes `explain_subset: null`, and
only `build-subset` fills it. Rebuilding the corpus without following up leaves the model layer
with no pinned subset to measure over.

Like `cli.py`, this is a composition root: the clock is read once, at the boundary, and the date
travels down as a value.
"""

from __future__ import annotations

from datetime import date, datetime
from pathlib import Path
from typing import Annotated

import typer

from emendrix.eu.cache import DiskResponseCache, FixtureResponseCache
from emendrix.eu.cellar import CellarClient
from emendrix.eu.fetch_fixtures import (
    EXTRA_PINS_NAME,
    PINNED,
    build_fixtures,
    merge_pins,
    write_extra_pins,
)
from emendrix.eu.http import CellarHttp, today_utc
from emendrix.eval_.build import build_corpus
from emendrix.eval_.corpus import CORPUS_PATH, CorpusCase, EvalCorpus, load_corpus, write_corpus
from emendrix.eval_.metrics import CaseResult
from emendrix.eval_.pins import RecordingCache, case_inputs, fixture_pins
from emendrix.eval_.runner import CorpusReader, prepare_case
from emendrix.eval_.subset import select_subset

__all__ = ["DEFAULT_FIXTURES", "build", "build_subset"]

DEFAULT_FIXTURES = Path("tests/fixtures/eu")


def build(
    fixtures: Annotated[
        Path, typer.Option("--fixtures", help="Fixture directory to pin the corpus into.")
    ] = DEFAULT_FIXTURES,
    out: Annotated[
        Path, typer.Option("--out", help="Where the generated corpus is written.")
    ] = CORPUS_PATH,
    fetch: Annotated[
        bool, typer.Option("--fetch/--no-fetch", help="Re-pin the fixture set from CELLAR.")
    ] = True,
    built_on: Annotated[
        datetime | None,
        typer.Option("--built-on", formats=["%Y-%m-%d"], help="Date to stamp the corpus with."),
    ] = None,
) -> None:
    """Select the labelled transitions from the acts' own notices, and pin what they need."""
    stamp = built_on.date() if built_on is not None else today_utc()
    http = CellarHttp(cache=DiskResponseCache())
    with http:
        client = CellarClient(http, observed_on=stamp)
        corpus = build_corpus(client, built_on=stamp)
        corpus, pins = fixture_pins(corpus, client)
    fixtures.mkdir(parents=True, exist_ok=True)
    write_extra_pins(
        fixtures / EXTRA_PINS_NAME,
        pins,
        note=(
            f"Generated by `emendrix eval build-corpus` on {stamp.isoformat()}: the documents "
            "the labelled corpus scores. Read and unioned with the hand-written set by "
            "`emendrix.eu.fetch_fixtures`."
        ),
    )
    if fetch:
        build_fixtures(fixtures, pins=merge_pins(PINNED, pins))
    corpus = corpus.model_copy(update={"cases": _with_inputs(corpus, fixtures, stamp)})
    write_corpus(corpus, out)
    typer.echo(
        f"{len(corpus.cases)} transitions, {len(corpus.skips)} skipped versions, "
        f"{len(pins)} pinned documents -> {out}"
    )


def _with_inputs(corpus: EvalCorpus, fixtures: Path, stamp: date) -> tuple[CorpusCase, ...]:
    """Pin each case's inputs by digest, offline, from the fixture set just written."""
    filled: list[CorpusCase] = []
    for case in corpus.cases:
        cache = RecordingCache(FixtureResponseCache(fixtures))
        client = CellarClient(CellarHttp(cache=cache), observed_on=stamp)
        filled.append(case.model_copy(update={"inputs": case_inputs(client, cache, case)}))
    return tuple(filled)


def build_subset(
    corpus_path: Annotated[
        Path, typer.Option("--corpus", help="The committed labelled set to select from.")
    ] = CORPUS_PATH,
    fixture_dir: Annotated[
        Path, typer.Option("--fixture-dir", help="The pinned fixture set to diff from.")
    ] = DEFAULT_FIXTURES,
    out: Annotated[
        Path, typer.Option("--out", help="Where the updated corpus is written.")
    ] = CORPUS_PATH,
) -> None:
    """Choose the pinned explanation subset the model layer is measured over. Offline.

    Reads the committed corpus and the committed fixtures, diffs every transition, and writes
    the selection rule's answer back into `corpus.json`. No network, no clock — the observation
    date is the corpus's own build date — and no model: this only decides *which* changes will
    later be recorded. Recording them is `uv run pytest -m "record and live" tests/eval`.
    """
    corpus = load_corpus(corpus_path)
    http = CellarHttp(cache=FixtureResponseCache(fixture_dir))
    deltas = []
    with http:
        reader = CorpusReader(CellarClient(http, observed_on=corpus.built_on))
        for case in corpus.cases:
            prepared = prepare_case(reader, case)
            if isinstance(prepared, CaseResult):
                continue
            deltas.append((case.id, prepared.corroboration.delta))
    subset = select_subset(deltas)
    write_corpus(corpus.model_copy(update={"explain_subset": subset}), out)
    typer.echo(
        f"{subset.changes} changes over {len(subset.cases)} transitions -> {out}\n{subset.note}"
    )
