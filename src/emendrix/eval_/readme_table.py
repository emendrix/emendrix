"""The README's metrics section, generated from the latest committed report and never by hand.

Every published number in this repository has git-visible provenance: it is read out of a dated
report JSON under `reports/eval/`, which was itself produced by a run anybody can repeat from the
committed corpus and the committed fixtures. The README section between the two sentinel comments
is a *rendering* of that file, so the workflow is:

```bash
uv run emendrix eval run              # measure, and write the dated report
uv run emendrix eval publish-readme   # regenerate the README section from it
```

Hand-editing between the sentinels is forbidden and is enforced rather than asked for:
`tests/eval/test_readme_table.py` regenerates the section and fails if the file differs. That
test exists to fight exactly one thing, a number in a README that nudged upward without a
measurement behind it, and it is the reason the caveat sentence rides in the same table row as
the figure it qualifies. Quoting a number without its limitation takes deleting a table cell.

**What each row says is not decided here.** The rows are `metric_rows.py`'s, because the site's
methodology page publishes the same figures and the two must not be able to disagree about what
they mean. This module is only the Markdown of them.

No clock: the date printed is the report's own run date.
"""

from __future__ import annotations

import json
from pathlib import Path

from emendrix.eval_.metric_rows import MetricRow, metric_rows
from emendrix.eval_.report import DEFAULT_REPORT_DIR
from emendrix.eval_.runner import EvalRun

__all__ = [
    "END",
    "START",
    "latest_report",
    "publish",
    "regenerate",
    "render_metrics",
    "splice",
]

START = "<!-- emendrix:metrics:start -->"
END = "<!-- emendrix:metrics:end -->"

_GENERATED = (
    "*Generated by `uv run emendrix eval publish-readme` from the report named below. "
    "Do not edit between the sentinel comments — a test regenerates this section and fails on "
    "any difference.*"
)


def _row(row: MetricRow) -> str:
    return f"| {row.measure} | {row.result} | {row.n} | {row.meaning} |"


def render_metrics(run: EvalRun, report: Path) -> str:
    """The whole README section, sentinels included. Pure: only the report decides its content."""
    link = f"./{report.with_suffix('.md').as_posix()}"
    lines = [
        START,
        "",
        _GENERATED,
        "",
        "| Measure | Result | n | What it means — and what it does not |",
        "|---|---|---|---|",
        *(_row(row) for row in metric_rows(run)),
        "",
        f"Measured on **{run.run_date.isoformat()}** at revision `{run.revision}`, from "
        f"[`{report.with_suffix('.md').as_posix()}`]({link}). The deterministic rows cover every "
        f"transition in the committed corpus ({run.metrics.cases_scored} of "
        f"{run.metrics.cases} scored); the model rows cover the pinned explanation subset only, "
        "because each change in it is one recorded call to a provider.",
        "",
        END,
    ]
    return "\n".join(lines)


def splice(readme: str, section: str) -> str:
    """Replace whatever is between the sentinels. A README without them is a caller error."""
    start = readme.find(START)
    end = readme.find(END)
    if start == -1 or end == -1 or end < start:
        raise ValueError(
            f"the README has no {START} … {END} block to write into; add the two comment "
            f"markers where the metrics section belongs"
        )
    return readme[:start] + section + readme[end + len(END) :]


def _relative(report: Path, readme: Path) -> Path:
    """The report as the README should link to it: relative to the README's own directory.

    An absolute path here would bake somebody's home directory into a committed file and make
    the regeneration test pass or fail depending on where the checkout lives.
    """
    try:
        return report.resolve().relative_to(readme.resolve().parent)
    except ValueError:
        return report


def latest_report(directory: Path = DEFAULT_REPORT_DIR) -> Path:
    """The newest committed report JSON, by the run date *inside* it.

    By its own date rather than by the filesystem's: a checkout has whatever timestamps git felt
    like giving it, and a published number may not depend on that. Two reports sharing the newest
    date is refused rather than broken alphabetically: one of them is a re-score of the other, a
    rule that guesses which would eventually guess wrong, and the wrong guess publishes stale
    numbers.
    """
    found = sorted(directory.glob("*.json"))
    if not found:
        raise FileNotFoundError(f"no report JSON under {directory}; run `emendrix eval run` first")
    dated = [(str(json.loads(path.read_bytes())["run_date"]), path) for path in found]
    newest = max(day for day, _ in dated)
    same_day = [path for day, path in dated if day == newest]
    if len(same_day) > 1:
        names = ", ".join(path.name for path in same_day)
        raise ValueError(
            f"{len(same_day)} reports are dated {newest} ({names}); a re-score on the same date "
            f"supersedes the earlier one — remove it, or move one of the two"
        )
    return same_day[0]


def regenerate(
    readme: Path = Path("README.md"), directory: Path = DEFAULT_REPORT_DIR
) -> tuple[str, str, Path]:
    """`(what the file says now, what it should say, which report decided)`. Writes nothing.

    Split from `publish` so the check mode of the CLI — and the test that enforces this — can
    ask "is it current?" without touching the file it is asking about.
    """
    report = latest_report(directory)
    run = EvalRun.model_validate_json(report.read_bytes())
    current = readme.read_text(encoding="utf-8")
    return current, splice(current, render_metrics(run, _relative(report, readme))), report


def publish(
    readme: Path = Path("README.md"), directory: Path = DEFAULT_REPORT_DIR
) -> tuple[bool, Path]:
    """Rewrite the README's metrics section from the latest report. `(changed, report path)`."""
    current, updated, report = regenerate(readme, directory)
    if updated == current:
        return False, report
    readme.write_text(updated, encoding="utf-8")
    return True, report
